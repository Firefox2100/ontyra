"""Generate the configuration reference (English and Chinese) from `Settings`; `--check` fails
when either file is stale."""

from __future__ import annotations

import sys
import typing
from pathlib import Path

from pydantic import BaseModel
from pydantic.fields import FieldInfo

from ontyra.config import Settings

ROOT = Path(__file__).resolve().parent.parent
TARGETS = {
    "en": ROOT / "docs/docs/reference/configuration.md",
    "zh": ROOT
    / "docs/i18n/zh-Hans/docusaurus-plugin-content-docs/current/reference/configuration.md",
}

HEADERS = {
    "en": """---
title: Configuration reference
---

{/* Generated by scripts/export_settings_docs.py from ontyra.config.Settings. Do not edit. */}

Every setting is an environment variable with the `ONTYRA_` prefix; `__` separates nested names
(`ONTYRA_DB__URL`). A `.env` file in the working directory is read too. Values for lists and
objects are JSON. The defaults are what the code uses when nothing is set.

""",
    "zh": """---
title: 配置参考
---

{/* Generated by scripts/export_settings_docs.py from ontyra.config.Settings. Do not edit. */}

每一项设置都是一个带 `ONTYRA_` 前缀的环境变量；`__` 用来分隔嵌套的名字（`ONTYRA_DB__URL`）。
工作目录中的 `.env` 文件也会被读取。列表和对象的值使用 JSON。默认值是在什么都没设置时代码所使用的值。

""",
}
COLUMNS = {"en": "Variable | Type | Default", "zh": "变量 | 类型 | 默认值"}


def _model_of(annotation: object) -> type[BaseModel] | None:
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation
    for arg in typing.get_args(annotation):
        found = _model_of(arg)
        if found is not None:
            return found
    return None


def _default(info: FieldInfo) -> str:
    if info.default_factory is not None:
        return "(computed)"
    value = info.default
    if type(value).__name__ == "SecretStr":
        return "secret"
    if value is None:
        return "unset"
    if isinstance(value, str):
        return f"`{value}`" if value else "empty"
    return f"`{value!r}`".replace("|", "\\|")


def _type(annotation: object) -> str:
    if typing.get_origin(annotation) is typing.Literal:
        return " \\| ".join(f"`{a}`" for a in typing.get_args(annotation))
    text = getattr(annotation, "__name__", None) or str(annotation)
    return text.replace("typing.", "").replace("|", "\\|")


def _rows(model: type[BaseModel], prefix: str) -> list[tuple[str, str, str]]:
    rows: list[tuple[str, str, str]] = []
    for name, info in model.model_fields.items():
        nested = _model_of(info.annotation)
        env = f"{prefix}{name.upper()}"
        if nested is not None and info.annotation is nested:
            rows.extend(_rows(nested, f"{env}__"))
        else:
            rows.append((env, _type(info.annotation), _default(info)))
    return rows


def render(lang: str = "en") -> str:
    sections: dict[str, list[tuple[str, str, str]]] = {"general": []}
    for name, info in Settings.model_fields.items():
        nested = _model_of(info.annotation)
        if nested is not None and info.annotation is nested:
            sections[name] = _rows(nested, f"ONTYRA_{name.upper()}__")
        else:
            sections["general"].append(
                (f"ONTYRA_{name.upper()}", _type(info.annotation), _default(info))
            )
    out = [HEADERS[lang]]
    for name, rows in sections.items():
        if not rows:
            continue
        out.append(f"## {name}\n\n| {COLUMNS[lang]} |\n|---|---|---|\n")
        out.extend(f"| `{env}` | {kind} | {default} |\n" for env, kind, default in rows)
        out.append("\n")
    return "".join(out)


def main() -> int:
    check = "--check" in sys.argv
    stale = False
    for lang, target in TARGETS.items():
        text = render(lang)
        if check:
            current = target.read_text(encoding="utf-8") if target.exists() else ""
            if current != text:
                print(
                    f"configuration reference is stale ({target.name}, {lang}): run scripts/export_settings_docs.py"
                )
                stale = True
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
