"""Small deterministic text helpers for lexical relevance (no model, no corpus statistics)."""

from __future__ import annotations

import re

STOPWORDS = frozenset(
    [
        "a",
        "an",
        "and",
        "are",
        "as",
        "at",
        "be",
        "been",
        "but",
        "by",
        "can",
        "could",
        "did",
        "do",
        "does",
        "for",
        "from",
        "had",
        "has",
        "have",
        "how",
        "i",
        "if",
        "in",
        "into",
        "is",
        "it",
        "its",
        "me",
        "my",
        "of",
        "on",
        "or",
        "our",
        "should",
        "so",
        "that",
        "the",
        "their",
        "them",
        "then",
        "there",
        "these",
        "they",
        "this",
        "to",
        "up",
        "us",
        "was",
        "we",
        "were",
        "what",
        "when",
        "where",
        "which",
        "who",
        "why",
        "will",
        "with",
        "would",
        "you",
        "your",
    ]
)
_SUFFIXES = ("ing", "ed", "es", "s")


def stem(word: str) -> str:
    for suffix in _SUFFIXES:
        if word.endswith(suffix) and len(word) - len(suffix) >= 3:
            return word[: -len(suffix)]
    return word


def content_tokens(text: str) -> set[str]:
    """Lower-cased, stop-word-free, lightly stemmed word set."""
    return {stem(w) for w in re.findall(r"[\w]+", text.casefold()) if w not in STOPWORDS}


def coverage(query: str, text: str) -> float:
    """Fraction of the query's content words that occur in `text` (0 when the query has none)."""
    q = content_tokens(query)
    return len(q & content_tokens(text)) / len(q) if q else 0.0
